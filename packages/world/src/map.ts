export const TEST_MAP_ID = "starter-valley";

export function getChunkId(x: number, z: number): string {
  return `${x}:${z}`;
}

export function getChunkAt(chunkX: number, chunkZ: number): TerrainChunkDTO {
  const startRow = chunkZ * CHUNK_SIZE;
  const startColumn = chunkX * CHUNK_SIZE;
  const chunkHeights = heights
    .slice(startRow, startRow + CHUNK_SIZE)
    .map((row) => row.slice(startColumn, startColumn + CHUNK_SIZE));

  return {
    id: getChunkId(chunkX, chunkZ),
    x: chunkX,
    z: chunkZ,
    size: CHUNK_SIZE,
    heights: chunkHeights,
  };
}

export function getInitialChunks(): TerrainChunkDTO[] {
  return [getChunkAt(0, 0), getChunkAt(1, 0), getChunkAt(0, 1), getChunkAt(1, 1)];
}

export function getHeightAt(x: number, z: number): number {
  const row = Math.max(0, Math.min(heights.length - 1, Math.floor(z)));
  const column = Math.max(0, Math.min(heights[0].length - 1, Math.floor(x)));
  return heights[row][column];
}

export function getNeighborChunks(centerChunkId: string): TerrainChunkDTO[] {
  const [chunkX, chunkZ] = centerChunkId.split(":").map(Number);
  const chunks: TerrainChunkDTO[] = [];
  for (let dz = -1; dz <= 1; dz += 1) {
    for (let dx = -1; dx <= 1; dx += 1) {
      const nextX = chunkX + dx;
      const nextZ = chunkZ + dz;
      if (nextX < 0 || nextZ < 0 || nextX > 1 || nextZ > 1) {
        continue;
      }
      chunks.push(getChunkAt(nextX, nextZ));
    }
  }
  return chunks;
}

export function resolveChunkIdForPosition(x: number, z: number): string {
  return getChunkId(Math.floor(x / CHUNK_SIZE), Math.floor(z / CHUNK_SIZE));
}
